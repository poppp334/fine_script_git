def build_pairs():
    pairs = []
    for questions, answer in TOPICS:
        for question in questions:
            pairs.append(
                {
                    "messages": [
                        {"role": "user", "content": question},
                        {"role": "assistant", "content": answer},
                    ]
                }
            )
    for question, answer in CHITCHAT:
        pairs.append(
            {
                "messages": [
                    {"role": "user", "content": question},
                    {"role": "assistant", "content": answer},
                ]
            }
        )
    return pairs


def write_jsonl(path, entries):
    text = "\n".join(json.dumps(entry, ensure_ascii=False) for entry in entries)
    path.write_text(text + "\n", encoding="utf-8")


def write_prompts_csv(path, prompts):
    lines = ["prompt"] + ['"' + prompt.replace('"', '""') + '"' for prompt in prompts]
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main():
    parser = argparse.ArgumentParser(description="Generate Demo 1 synthetic dataset")
    parser.add_argument("--out-dir", default=str(Path(__file__).resolve().parent))
    parser.add_argument("--val-split", type=float, default=0.15)
    parser.add_argument("--seed", type=int, default=42)
    args = parser.parse_args()

    out_dir = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    pairs = build_pairs()
    rng = random.Random(args.seed)
    rng.shuffle(pairs)
    n_val = max(1, round(len(pairs) * args.val_split))
    val_pairs = pairs[:n_val]
    train_pairs = pairs[n_val:]
    # guarantee no identical question in both splits
    val_questions = {p["messages"][0]["content"] for p in val_pairs}
    train_pairs = [p for p in train_pairs if p["messages"][0]["content"] not in val_questions]

    write_jsonl(out_dir / "train.jsonl", train_pairs)
    write_jsonl(out_dir / "val.jsonl", val_pairs)
    write_prompts_csv(out_dir / "prompts.csv", PROMPTS)
    write_prompts_csv(out_dir / "regression.csv", REGRESSION)

    print(
        json.dumps(
            {
                "train": len(train_pairs),
                "val": len(val_pairs),
                "prompts": len(PROMPTS),
                "regression": len(REGRESSION),
                "out_dir": str(out_dir),
            },
            ensure_ascii=False,
        )
    )


if __name__ == "__main__":
    main()
